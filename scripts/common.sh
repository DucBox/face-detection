#!/bin/bash
# Shared settings for scripts/*.sh. Every value can be overridden by an env var of the same name.
set -euo pipefail

REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
PYTHON="${PYTHON:-python3}"
DATA_ROOT="${DATA_ROOT:-$REPO/datasets/widerface}"   # unpacked dataset: images/{train,val}, labels/{train,val}
DATA_YAML="$REPO/data/widerface_run.yaml"             # generated, points at DATA_ROOT

# Physical GPU ids to use, e.g. GPUS=2 or GPUS=0,1,2,3 (or GPUS=cpu). Falls back to DEVICE / CUDA_VISIBLE_DEVICES.
GPUS="${GPUS:-${DEVICE:-${CUDA_VISIBLE_DEVICES:-0}}}"
if [ "$GPUS" = "cpu" ]; then
  export CUDA_VISIBLE_DEVICES=""
else
  export CUDA_VISIBLE_DEVICES="$GPUS"
fi

log() { echo "[$(date '+%F %T')] $*"; }

write_data_yaml() {
  cat > "$DATA_YAML" <<EOF
# generated by scripts/common.sh
train: $DATA_ROOT/images/train  # 12880 images
val: $DATA_ROOT/images/val  # 3226 images
is_coco: False
nc: 1
names: ['face']
EOF
}
